import { NextRequest, NextResponse } from 'next/server';

/* ---------------------------------------------------------------------------
 * Report data loader – fetches from the sibling GET /api/reports/[id] route
 * so we stay in sync with whatever demo data the app provides.
 * -------------------------------------------------------------------------- */

interface ReportSection {
  id: string;
  title: string;
  content: string;
  status: string;
  wordCount?: number;
}

interface ReportData {
  id: string;
  title: string;
  template?: string;
  status: string;
  createdAt: string;
  updatedAt: string;
  sections: ReportSection[];
}

async function loadReport(
  id: string,
  request: NextRequest
): Promise<ReportData | null> {
  try {
    // Build the absolute URL for the sibling route
    const url = new URL(`/api/reports/${id}`, request.nextUrl.origin);
    const res = await fetch(url.toString());
    if (!res.ok) return null;
    return (await res.json()) as ReportData;
  } catch {
    return null;
  }
}

/* ---------------------------------------------------------------------------
 * Helpers
 * -------------------------------------------------------------------------- */

/** Build full markdown from a report */
function reportToMarkdown(report: ReportData): string {
  const date = new Date(report.updatedAt || report.createdAt).toLocaleDateString(
    'en-GB',
    { day: 'numeric', month: 'long', year: 'numeric' }
  );

  const header =
    `# ${report.title}\n\n` +
    `*Generated by TACITUS / PRAXIS — ${date}*\n\n` +
    `---\n\n`;

  const body = report.sections
    .map((s) => {
      const content = s.content?.trim() || '_No content yet._';
      return `## ${s.title}\n\n${content}`;
    })
    .join('\n\n---\n\n');

  return header + body + '\n';
}

/** Strip markdown to plain text (for PDF) */
function stripMd(md: string): string {
  return md
    .replace(/#{1,6}\s+/g, '')
    .replace(/\*\*(.+?)\*\*/g, '$1')
    .replace(/\*(.+?)\*/g, '$1')
    .replace(/`(.+?)`/g, '$1')
    .replace(/^\s*[-*+]\s+/gm, '  \u2022 ')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

/* ---------------------------------------------------------------------------
 * PDF generation via jsPDF
 * -------------------------------------------------------------------------- */

async function generatePdf(report: ReportData): Promise<Buffer> {
  // Dynamic import — will fail gracefully if package not installed
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  let jsPDFConstructor: any;
  try {
    const mod = await import('jspdf');
    jsPDFConstructor = mod.jsPDF || mod.default;
  } catch {
    throw new Error(
      'PDF export requires the jspdf package. Run: npm install jspdf'
    );
  }

  const doc = new jsPDFConstructor({ unit: 'mm', format: 'a4' });
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 20;
  const usableWidth = pageWidth - margin * 2;
  let y = margin;

  const EMERALD = '#10B981';
  const DARK = '#111827';
  const GRAY = '#6B7280';

  const date = new Date(report.updatedAt || report.createdAt).toLocaleDateString(
    'en-GB',
    { day: 'numeric', month: 'long', year: 'numeric' }
  );

  /* --- helper: add page number footer --- */
  function addFooter(pageNum: number, totalPlaceholder?: boolean) {
    doc.setFontSize(8);
    doc.setTextColor(GRAY);
    const footer = totalPlaceholder
      ? `Page ${pageNum}`
      : `Page ${pageNum}`;
    doc.text(footer, pageWidth / 2, pageHeight - 10, { align: 'center' });
    doc.text('TACITUS / PRAXIS', margin, pageHeight - 10);
    doc.text(date, pageWidth - margin, pageHeight - 10, { align: 'right' });
  }

  /* --- helper: ensure space, add page if needed --- */
  function ensureSpace(needed: number) {
    if (y + needed > pageHeight - 20) {
      addFooter(doc.getNumberOfPages());
      doc.addPage();
      y = margin;
    }
  }

  /* --- Title page header --- */
  // Emerald accent line
  doc.setDrawColor(EMERALD);
  doc.setLineWidth(1.2);
  doc.line(margin, y, pageWidth - margin, y);
  y += 6;

  // "TACITUS" label
  doc.setFontSize(10);
  doc.setTextColor(EMERALD);
  doc.setFont('helvetica', 'bold');
  doc.text('TACITUS', margin, y);
  y += 3;

  // Thin accent line
  doc.setLineWidth(0.3);
  doc.line(margin, y, margin + 20, y);
  y += 8;

  // Report title
  doc.setFontSize(22);
  doc.setTextColor(DARK);
  doc.setFont('helvetica', 'bold');
  const titleLines: string[] = doc.splitTextToSize(report.title, usableWidth);
  doc.text(titleLines, margin, y);
  y += titleLines.length * 9 + 4;

  // Date
  doc.setFontSize(10);
  doc.setTextColor(GRAY);
  doc.setFont('helvetica', 'normal');
  doc.text(date, margin, y);
  y += 4;

  // Status badge
  doc.text(`Status: ${(report.status || 'draft').toUpperCase()}`, margin, y);
  y += 10;

  // Separator
  doc.setDrawColor(EMERALD);
  doc.setLineWidth(0.5);
  doc.line(margin, y, pageWidth - margin, y);
  y += 10;

  /* --- Sections --- */
  for (const section of report.sections) {
    ensureSpace(30);

    // Section heading
    doc.setFontSize(14);
    doc.setTextColor(EMERALD);
    doc.setFont('helvetica', 'bold');
    doc.text(section.title, margin, y);
    y += 3;

    // Thin underline
    doc.setDrawColor(EMERALD);
    doc.setLineWidth(0.3);
    doc.line(margin, y, margin + 40, y);
    y += 6;

    // Section body
    const bodyText = section.content?.trim()
      ? stripMd(section.content)
      : '(No content yet)';

    doc.setFontSize(10);
    doc.setTextColor(DARK);
    doc.setFont('helvetica', 'normal');

    const lines: string[] = doc.splitTextToSize(bodyText, usableWidth);
    for (const line of lines) {
      ensureSpace(6);
      doc.text(line, margin, y);
      y += 5;
    }

    y += 8;
  }

  // Add footer to all pages
  const totalPages = doc.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    addFooter(i);
  }

  // Return as buffer
  const arrayBuffer = doc.output('arraybuffer');
  return Buffer.from(arrayBuffer);
}

/* ---------------------------------------------------------------------------
 * DOCX generation via docx package
 * -------------------------------------------------------------------------- */

async function generateDocx(report: ReportData): Promise<Buffer> {
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  let docxMod: any;
  try {
    docxMod = await import('docx');
  } catch {
    throw new Error(
      'DOCX export requires the docx package. Run: npm install docx'
    );
  }

  const {
    Document,
    Packer,
    Paragraph,
    TextRun,
    HeadingLevel,
    AlignmentType,
    BorderStyle,
    PageNumber,
    NumberFormat,
    Footer,
  } = docxMod;

  const date = new Date(report.updatedAt || report.createdAt).toLocaleDateString(
    'en-GB',
    { day: 'numeric', month: 'long', year: 'numeric' }
  );

  // Build section children
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  const children: any[] = [];

  // TACITUS header
  children.push(
    new Paragraph({
      children: [
        new TextRun({
          text: 'TACITUS',
          bold: true,
          color: '10B981',
          size: 20,
          font: 'Calibri',
        }),
      ],
      spacing: { after: 40 },
    })
  );

  // Emerald rule
  children.push(
    new Paragraph({
      border: {
        bottom: {
          color: '10B981',
          space: 1,
          size: 6,
          style: BorderStyle.SINGLE,
        },
      },
      spacing: { after: 200 },
    })
  );

  // Title
  children.push(
    new Paragraph({
      children: [
        new TextRun({
          text: report.title,
          bold: true,
          size: 44,
          font: 'Calibri',
          color: '111827',
        }),
      ],
      heading: HeadingLevel.TITLE,
      spacing: { after: 120 },
    })
  );

  // Date
  children.push(
    new Paragraph({
      children: [
        new TextRun({
          text: date,
          italics: true,
          size: 20,
          color: '6B7280',
          font: 'Calibri',
        }),
      ],
      spacing: { after: 80 },
    })
  );

  // Status
  children.push(
    new Paragraph({
      children: [
        new TextRun({
          text: `Status: ${(report.status || 'draft').toUpperCase()}`,
          size: 18,
          color: '6B7280',
          font: 'Calibri',
        }),
      ],
      spacing: { after: 300 },
    })
  );

  // Sections
  for (const section of report.sections) {
    // Section heading
    children.push(
      new Paragraph({
        children: [
          new TextRun({
            text: section.title,
            bold: true,
            size: 28,
            color: '10B981',
            font: 'Calibri',
          }),
        ],
        heading: HeadingLevel.HEADING_1,
        spacing: { before: 240, after: 120 },
        border: {
          bottom: {
            color: '10B981',
            space: 2,
            size: 2,
            style: BorderStyle.SINGLE,
          },
        },
      })
    );

    // Section content — split into paragraphs
    const content = section.content?.trim() || '(No content yet)';
    const paragraphs = content.split(/\n\n+/);

    for (const para of paragraphs) {
      const trimmed = para.trim();
      if (!trimmed) continue;

      // Detect sub-headings (lines starting with ## or ###)
      if (/^#{2,3}\s/.test(trimmed)) {
        const headingText = trimmed.replace(/^#{2,3}\s+/, '');
        children.push(
          new Paragraph({
            children: [
              new TextRun({
                text: headingText,
                bold: true,
                size: 24,
                color: '111827',
                font: 'Calibri',
              }),
            ],
            heading: HeadingLevel.HEADING_2,
            spacing: { before: 160, after: 80 },
          })
        );
      } else {
        // Regular paragraph — handle bold/italic inline
        const text = trimmed
          .replace(/\*\*(.+?)\*\*/g, '$1')
          .replace(/\*(.+?)\*/g, '$1')
          .replace(/`(.+?)`/g, '$1');

        children.push(
          new Paragraph({
            children: [
              new TextRun({
                text,
                size: 22,
                font: 'Calibri',
                color: '111827',
              }),
            ],
            spacing: { after: 120 },
          })
        );
      }
    }
  }

  // Build document
  const doc = new Document({
    sections: [
      {
        properties: {
          page: {
            margin: { top: 1440, right: 1440, bottom: 1440, left: 1440 },
            pageNumbers: { start: 1, formatType: NumberFormat.DECIMAL },
          },
        },
        footers: {
          default: new Footer({
            children: [
              new Paragraph({
                alignment: AlignmentType.CENTER,
                children: [
                  new TextRun({
                    text: 'TACITUS / PRAXIS  —  Page ',
                    size: 16,
                    color: '6B7280',
                    font: 'Calibri',
                  }),
                  new TextRun({
                    children: [PageNumber.CURRENT],
                    size: 16,
                    color: '6B7280',
                    font: 'Calibri',
                  }),
                ],
              }),
            ],
          }),
        },
        children,
      },
    ],
  });

  const buffer = await Packer.toBuffer(doc);
  return Buffer.from(buffer);
}

/* ---------------------------------------------------------------------------
 * POST handler
 * -------------------------------------------------------------------------- */

export async function POST(
  request: NextRequest,
  { params }: { params: Promise<{ id: string }> }
) {
  const { id } = await params;

  let body: { format?: string };
  try {
    body = await request.json();
  } catch {
    return NextResponse.json(
      { error: 'Invalid JSON body. Expected: { format: "pdf" | "docx" | "md" }' },
      { status: 400 }
    );
  }

  const format = (body.format || 'pdf').toLowerCase();

  if (!['pdf', 'docx', 'md'].includes(format)) {
    return NextResponse.json(
      { error: `Unsupported format "${format}". Supported: pdf, docx, md` },
      { status: 400 }
    );
  }

  // Load report
  const report = await loadReport(id, request);
  if (!report) {
    return NextResponse.json(
      { error: `Report "${id}" not found.` },
      { status: 404 }
    );
  }

  const safeFilename = report.title
    .replace(/[^a-zA-Z0-9 _-]/g, '')
    .replace(/\s+/g, '-')
    .substring(0, 80);

  try {
    /* --- Markdown --- */
    if (format === 'md') {
      const md = reportToMarkdown(report);
      return new NextResponse(md, {
        status: 200,
        headers: {
          'Content-Type': 'text/markdown; charset=utf-8',
          'Content-Disposition': `attachment; filename="${safeFilename}.md"`,
        },
      });
    }

    /* --- PDF --- */
    if (format === 'pdf') {
      const pdfBuffer = await generatePdf(report);
      return new NextResponse(pdfBuffer, {
        status: 200,
        headers: {
          'Content-Type': 'application/pdf',
          'Content-Disposition': `attachment; filename="${safeFilename}.pdf"`,
        },
      });
    }

    /* --- DOCX --- */
    if (format === 'docx') {
      const docxBuffer = await generateDocx(report);
      return new NextResponse(docxBuffer, {
        status: 200,
        headers: {
          'Content-Type':
            'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
          'Content-Disposition': `attachment; filename="${safeFilename}.docx"`,
        },
      });
    }
  } catch (err: unknown) {
    const message = err instanceof Error ? err.message : 'Export failed';
    return NextResponse.json({ error: message }, { status: 500 });
  }

  return NextResponse.json({ error: 'Unexpected error' }, { status: 500 });
}
