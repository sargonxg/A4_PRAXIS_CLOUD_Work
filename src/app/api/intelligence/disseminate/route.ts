/**
 * Dissemination Engine — Part 4 P20
 *
 * Compiles tool outputs for a situation into a structured intelligence
 * product ready for external dissemination: PDF-ready JSON, markdown
 * digest, or raw JSON package.
 *
 * POST /api/intelligence/disseminate
 * {
 *   situationId: string;
 *   format: 'json' | 'markdown' | 'digest';
 *   tools?: string[];   // specific tools to include (default: all)
 *   classification?: 'unclassified' | 'sensitive' | 'confidential';
 * }
 *
 * Returns a structured package with metadata + selected tool outputs.
 */
import { NextResponse } from 'next/server';
import { getAdminDbOrThrow } from '@/lib/firebase/admin';
import { withAuth } from '@/lib/api/with-auth';
import { handleRouteError } from '@/lib/api/standard-error';
import type { Situation } from '@/types/situation';

export const maxDuration = 30;

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

function formatMarkdownSection(toolId: string, data: Record<string, unknown>): string {
  const title = toolId.replace(/_/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase());
  const lines = [`## ${title}`, ''];

  // Handle common output shapes
  if (typeof data.summary === 'string') lines.push(data.summary, '');
  if (typeof data.assessment === 'string') lines.push(data.assessment, '');
  if (typeof data.content === 'string') lines.push(data.content, '');

  // Array fields rendered as bullets
  for (const [key, value] of Object.entries(data)) {
    if (key === 'generatedAt' || key === 'situationId') continue;
    if (Array.isArray(value) && value.length > 0 && typeof value[0] === 'string') {
      lines.push(`**${key.replace(/_/g, ' ')}:**`);
      value.forEach((item: string) => lines.push(`- ${item}`));
      lines.push('');
    }
  }

  return lines.join('\n');
}

function formatDigest(
  situation: Situation,
  toolOutputs: Record<string, Record<string, unknown>>,
  classification: string,
): string {
  const date = new Date().toLocaleDateString('en-US', { weekday: 'long', year: 'numeric', month: 'long', day: 'numeric' });
  const lines = [
    `# INTELLIGENCE DIGEST`,
    `**${classification.toUpperCase()}**`,
    '',
    `**Situation:** ${situation.name}`,
    `**Region:** ${situation.region || 'Unspecified'}`,
    `**Generated:** ${date}`,
    `**Status:** ${situation.status}`,
    `**Glasl Stage:** ${situation.glaslStage || 'Not assessed'}/9`,
    '',
    '---',
    '',
  ];

  // Priority sections first
  const PRIORITY_ORDER = ['risk_assessment', 'early_warning', 'escalation_scan', 'stakeholder_map'];
  const remaining = Object.keys(toolOutputs).filter((k) => !PRIORITY_ORDER.includes(k));
  const ordered = [...PRIORITY_ORDER.filter((k) => toolOutputs[k]), ...remaining];

  for (const toolId of ordered) {
    const data = toolOutputs[toolId];
    if (!data) continue;
    lines.push(formatMarkdownSection(toolId, data));
    lines.push('---', '');
  }

  lines.push(`*Generated by PRAXIS Conflict Intelligence Platform — ${classification}*`);
  return lines.join('\n');
}

// ---------------------------------------------------------------------------
// Route handler
// ---------------------------------------------------------------------------

export const POST = withAuth(async (request, user) => {
  try {
    const body = await request.json() as {
      situationId: string;
      format?: 'json' | 'markdown' | 'digest';
      tools?: string[];
      classification?: 'unclassified' | 'sensitive' | 'confidential';
    };

    const { situationId, format = 'json', tools, classification = 'unclassified' } = body;

    if (!situationId) {
      return NextResponse.json({ error: 'situationId required' }, { status: 400 });
    }

    const db = getAdminDbOrThrow();
    const sitPath = `users/${user.uid}/situations/${situationId}`;

    // Load situation metadata
    const sitDoc = await db.doc(sitPath).get();
    if (!sitDoc.exists) {
      return NextResponse.json({ error: 'Situation not found' }, { status: 404 });
    }
    const situation = { id: sitDoc.id, ...sitDoc.data() } as Situation;

    // Load tool outputs
    const toolsSnap = await db.collection(`${sitPath}/tools`).get();
    const allToolOutputs: Record<string, Record<string, unknown>> = {};
    for (const doc of toolsSnap.docs) {
      allToolOutputs[doc.id] = doc.data() as Record<string, unknown>;
    }

    // Filter to requested tools if specified
    const selectedOutputs = tools && tools.length > 0
      ? Object.fromEntries(tools.filter((t) => allToolOutputs[t]).map((t) => [t, allToolOutputs[t]]))
      : allToolOutputs;

    const toolCount = Object.keys(selectedOutputs).length;

    // Package metadata
    const packageMeta = {
      packageId: `${situationId}_${Date.now()}`,
      classification,
      generatedAt: new Date().toISOString(),
      generatedBy: user.uid,
      situation: {
        id: situation.id,
        name: situation.name,
        region: situation.region,
        type: situation.type,
        status: situation.status,
        glaslStage: situation.glaslStage,
        riskScore: situation.riskScore,
        actors: situation.actors,
      },
      toolCount,
      tools: Object.keys(selectedOutputs),
    };

    if (format === 'json') {
      return NextResponse.json({
        ...packageMeta,
        outputs: selectedOutputs,
      });
    }

    if (format === 'markdown' || format === 'digest') {
      const md = format === 'digest'
        ? formatDigest(situation, selectedOutputs, classification)
        : Object.entries(selectedOutputs).map(([id, data]) => formatMarkdownSection(id, data)).join('\n\n---\n\n');

      return new Response(md, {
        headers: {
          'Content-Type': 'text/markdown; charset=utf-8',
          'Content-Disposition': `attachment; filename="${situation.name.replace(/[^a-z0-9]/gi, '_')}_intel_digest.md"`,
          'X-Package-Id': packageMeta.packageId,
          'X-Tool-Count': String(toolCount),
          'X-Classification': classification,
        },
      });
    }

    return NextResponse.json({ error: 'Invalid format' }, { status: 400 });
  } catch (err) {
    return handleRouteError(err, 'intelligence/disseminate');
  }
});
