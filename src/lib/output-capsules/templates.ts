export function getOutputCapsuleTemplate(templateId: string) {
  return OUTPUT_CAPSULE_TEMPLATES.find((template) => template.id === templateId) ?? null;
}

export function getOutputTemplatesForTool(toolId: string) {
  return OUTPUT_CAPSULE_TEMPLATES.filter((template) => (
    template.producibleBy.some((producer) => producer.kind === 'tool' && producer.id === toolId)
  ));
}
