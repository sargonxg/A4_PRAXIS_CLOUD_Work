/**
 * Export Service — PRAXIS
 * Utilities for exporting AI-generated and user-created content.
 */

/** Download a string as a file */
function downloadFile(content: string, filename: string, mimeType: string) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

/** Copy text to clipboard */
export async function copyToClipboard(text: string): Promise<boolean> {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    // Fallback for older browsers
    const textarea = document.createElement('textarea');
    textarea.value = text;
    textarea.style.position = 'fixed';
    textarea.style.opacity = '0';
    document.body.appendChild(textarea);
    textarea.select();
    const success = document.execCommand('copy');
    document.body.removeChild(textarea);
    return success;
  }
}

/** Export a conversation or AI content as markdown */
export function exportMarkdown(content: string, filename?: string) {
  const name = filename ?? `praxis-export-${Date.now()}.md`;
  downloadFile(content, name, 'text/markdown');
}

/** Export talking points as formatted text */
export function exportTalkingPoints(title: string, points: string[]): void {
  const content = `# ${title}\n\n${points.map((p, i) => `${i + 1}. ${p}`).join('\n')}`;
  downloadFile(content, `talking-points-${Date.now()}.md`, 'text/markdown');
}

/** Export talking points as plain text */
export function exportTalkingPointsPlain(title: string, points: string[]): string {
  return `${title}\n\n${points.map((p, i) => `${i + 1}. ${p}`).join('\n')}`;
}

/** Export a conflict graph as JSON */
export function exportConflictGraphJSON(graphData: unknown, conflictName: string): void {
  const content = JSON.stringify(graphData, null, 2);
  const filename = `conflict-graph-${conflictName.toLowerCase().replace(/\s+/g, '-')}-${Date.now()}.json`;
  downloadFile(content, filename, 'application/json');
}

/** Export entities as CSV */
export function exportEntitiesCSV(entities: Array<Record<string, unknown>>, filename?: string): void {
  if (entities.length === 0) return;
  const headers = Object.keys(entities[0]);
  const rows = entities.map((e) =>
    headers.map((h) => {
      const val = String(e[h] ?? '');
      return val.includes(',') ? `"${val.replace(/"/g, '""')}"` : val;
    }).join(',')
  );
  const csv = [headers.join(','), ...rows].join('\n');
  downloadFile(csv, filename ?? `entities-${Date.now()}.csv`, 'text/csv');
}

/** Export a report as markdown */
export function exportReport(title: string, sections: Array<{ heading: string; content: string }>): void {
  const md = `# ${title}\n\n*Generated by PRAXIS — ${new Date().toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric' })}*\n\n---\n\n` +
    sections.map((s) => `## ${s.heading}\n\n${s.content}`).join('\n\n---\n\n');
  downloadFile(md, `report-${Date.now()}.md`, 'text/markdown');
}

/** Format AI content for clipboard (strip markdown for plain text) */
export function stripMarkdown(md: string): string {
  return md
    .replace(/#{1,6}\s+/g, '')
    .replace(/\*\*(.+?)\*\*/g, '$1')
    .replace(/\*(.+?)\*/g, '$1')
    .replace(/`(.+?)`/g, '$1')
    .replace(/^\s*[-*+]\s+/gm, '• ')
    .replace(/^\s*\d+\.\s+/gm, '')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}
