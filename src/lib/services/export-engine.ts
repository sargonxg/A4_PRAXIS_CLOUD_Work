export function exportConflictGrammarJSON(entities: Record<string, unknown[]>, situation: Situation): string {
  return JSON.stringify({
    '@context': 'https://tacitus.me/aco/v2',
    '@type': 'ConflictGraph',
    situation: {
      name: situation.name,
      type: situation.type,
      region: situation.region,
      status: situation.status,
    },
    entities,
    exportedAt: new Date().toISOString(),
    generator: 'TACITUS PRAXIS',
  }, null, 2);
}

export function exportTimelineCSV(events: { date: string; title: string; type: string; actors: string[]; severity: string }[]): string {
  const header = 'Date,Title,Type,Actors,Severity\n';
  const rows = events.map((e) =>
    `"${e.date}","${e.title.replace(/"/g, '""')}","${e.type}","${e.actors.join('; ')}","${e.severity}"`
  ).join('\n');
  return header + rows;
}
