/**
 * PRAXIS Export Engine
 * Generates professional DOCX, PDF, and data exports
 */

import { Document, Packer, Paragraph, TextRun, HeadingLevel, AlignmentType, BorderStyle } from 'docx';
import type { Situation } from '@/types/situation';

// ============================================================================
// DOCX Generation
// ============================================================================

function headerParagraph(text: string, level: typeof HeadingLevel[keyof typeof HeadingLevel] = HeadingLevel.HEADING_1) {
  return new Paragraph({
    heading: level,
    children: [new TextRun({ text, font: 'EB Garamond', bold: true })],
    spacing: { before: 300, after: 100 },
  });
}

function bodyParagraph(text: string) {
  return new Paragraph({
    children: [new TextRun({ text, font: 'Inter', size: 22 })],
    spacing: { after: 120 },
  });
}

function metaParagraph(text: string) {
  return new Paragraph({
    children: [new TextRun({ text, font: 'Inter', size: 18, italics: true, color: '666666' })],
    spacing: { after: 60 },
  });
}

function divider() {
  return new Paragraph({
    border: { bottom: { style: BorderStyle.SINGLE, size: 1, color: 'CCCCCC' } },
    spacing: { before: 200, after: 200 },
  });
}

function normalizeSources(sources: unknown): string[] {
  if (!Array.isArray(sources)) return [];
  return sources
    .filter((source): source is string => typeof source === 'string')
    .map((source) => source.trim())
    .filter(Boolean);
}

function uniqueSources(...groups: unknown[]): string[] {
  const seen = new Set<string>();
  const result: string[] = [];
  for (const group of groups) {
    for (const source of normalizeSources(group)) {
      if (seen.has(source)) continue;
      seen.add(source);
      result.push(source);
    }
  }
  return result;
}

function normalizeSummary(value: unknown, fallbackSlides: Array<{ heading: string; content: string }>): string[] {
  if (Array.isArray(value)) {
    return value
      .filter((item): item is string => typeof item === 'string')
      .map((item) => item.trim())
      .filter(Boolean)
      .slice(0, 5);
  }
  if (typeof value === 'string' && value.trim()) {
    return value
      .split(/\n+/)
      .map((line) => line.replace(/^[-*•]\s*/, '').trim())
      .filter(Boolean)
      .slice(0, 5);
  }
  return fallbackSlides
    .slice(0, 5)
    .map((slide) => `${slide.heading}: ${slide.content.slice(0, 180).trim()}`)
    .filter(Boolean);
}

function numberedReferenceParagraph(index: number, source: string) {
  return metaParagraph(`[${index}] ${source}`);
}

/**
 * Generate a situation report as DOCX
 */
export async function generateSituationReportDOCX(
  situation: Situation,
  content: { executiveSummary: string; sections: { title: string; content: string }[]; sources: string[] }
): Promise<Buffer> {
  const sources = normalizeSources(content.sources);
  const sourceSummary = sources.length
    ? sources.join(', ')
    : 'No explicit source list was supplied with this export.';

  const doc = new Document({
    styles: {
      default: {
        document: {
          run: { font: 'Inter', size: 22 },
          paragraph: { spacing: { line: 276 } },
        },
      },
    },
    sections: [{
      properties: {
        page: {
          margin: { top: 1440, bottom: 1440, left: 1440, right: 1440 },
        },
      },
      children: [
        // Title page
        new Paragraph({ spacing: { before: 2000 } }),
        new Paragraph({
          alignment: AlignmentType.CENTER,
          children: [new TextRun({ text: 'SITUATION REPORT', font: 'EB Garamond', size: 36, bold: true })],
        }),
        new Paragraph({
          alignment: AlignmentType.CENTER,
          spacing: { before: 200 },
          children: [new TextRun({ text: situation.name, font: 'EB Garamond', size: 28 })],
        }),
        new Paragraph({
          alignment: AlignmentType.CENTER,
          spacing: { before: 400 },
          children: [new TextRun({ text: `Region: ${situation.region || 'N/A'} | Status: ${situation.status} | Risk Score: ${situation.riskScore}/10`, font: 'Inter', size: 20, color: '666666' })],
        }),
        new Paragraph({
          alignment: AlignmentType.CENTER,
          spacing: { before: 200 },
          children: [new TextRun({ text: `Generated by TACITUS PRAXIS | ${new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' })}`, font: 'Inter', size: 18, italics: true, color: '999999' })],
        }),

        // Page break
        new Paragraph({ pageBreakBefore: true }),

        // Executive Summary
        headerParagraph('Executive Summary'),
        bodyParagraph(content.executiveSummary),
        divider(),

        // Key Actors
        headerParagraph('Key Actors', HeadingLevel.HEADING_2),
        ...situation.actors.map((a) => new Paragraph({
          children: [new TextRun({ text: `• ${a}`, font: 'Inter', size: 22 })],
          spacing: { after: 60 },
        })),
        divider(),

        // Content sections
        ...content.sections.flatMap((section) => [
          headerParagraph(section.title, HeadingLevel.HEADING_2),
          bodyParagraph(section.content),
        ]),

        // Sources
        divider(),
        headerParagraph('Sources', HeadingLevel.HEADING_2),
        ...(sources.length
          ? sources.map((s) => metaParagraph(`• ${s}`))
          : [metaParagraph('No explicit source list was supplied with this export. Verify citations before external distribution.')]),

        // Footer
        divider(),
        metaParagraph('This report was generated by TACITUS PRAXIS — Conflict Intelligence Platform'),
        metaParagraph(`Source basis: ${sourceSummary} | ${new Date().toISOString()}`),
      ],
    }],
  });

  return Buffer.from(await Packer.toBuffer(doc));
}

/**
 * Generate a briefing note as DOCX
 */
export async function generateBriefingDOCX(
  situation: Situation,
  briefing: {
    title: string;
    slides: { heading: string; content: string }[];
    author?: string;
    classification?: string;
    executiveSummary?: string | string[];
    sources?: string[];
    calibration?: {
      promptHealthScore?: number;
      acoEntityCounts?: Record<string, number>;
      model?: string;
      generatedAt?: string;
    };
  }
): Promise<Buffer> {
  const slides = Array.isArray(briefing.slides) ? briefing.slides : [];
  const sources = uniqueSources(briefing.sources, situation.sourceUrls, situation.customSources?.map((source) => source.url));
  const summaryBullets = normalizeSummary(briefing.executiveSummary, slides);
  const generatedAt = briefing.calibration?.generatedAt ?? new Date().toISOString();
  const classification = briefing.classification ?? 'Working product';

  const doc = new Document({
    sections: [{
      properties: {
        page: { margin: { top: 1440, bottom: 1440, left: 1440, right: 1440 } },
      },
      children: [
        new Paragraph({
          alignment: AlignmentType.CENTER,
          spacing: { before: 760, after: 120 },
          children: [new TextRun({ text: 'BRIEFING NOTE', font: 'EB Garamond', size: 36, bold: true })],
        }),
        new Paragraph({
          alignment: AlignmentType.CENTER,
          children: [new TextRun({ text: briefing.title, font: 'EB Garamond', size: 28 })],
          spacing: { after: 100 },
        }),
        new Paragraph({
          alignment: AlignmentType.CENTER,
          children: [new TextRun({ text: `${situation.name} | ${situation.region} | ${classification}`, font: 'Inter', size: 20, color: '666666' })],
          spacing: { after: 80 },
        }),
        new Paragraph({
          alignment: AlignmentType.CENTER,
          children: [new TextRun({ text: `Prepared by ${briefing.author ?? 'PRAXIS'} | ${new Date(generatedAt).toLocaleDateString()}`, font: 'Inter', size: 18, italics: true, color: '666666' })],
          spacing: { after: 280 },
        }),
        divider(),
        headerParagraph('Executive Summary', HeadingLevel.HEADING_2),
        ...(summaryBullets.length
          ? summaryBullets.map((item) => new Paragraph({
            children: [new TextRun({ text: `• ${item}`, font: 'Inter', size: 22 })],
            spacing: { after: 80 },
          }))
          : [bodyParagraph('No executive summary was supplied with this export.')]),
        divider(),
        headerParagraph('Body Sections', HeadingLevel.HEADING_2),
        ...slides.flatMap((slide) => [
          headerParagraph(slide.heading, HeadingLevel.HEADING_2),
          bodyParagraph(slide.content),
        ]),
        divider(),
        headerParagraph('Source References', HeadingLevel.HEADING_2),
        ...(sources.length
          ? sources.map((source, index) => numberedReferenceParagraph(index + 1, source))
          : [metaParagraph('[1] No explicit source references were supplied. Verify before distribution.')]),
        divider(),
        headerParagraph('Calibration Footer', HeadingLevel.HEADING_2),
        metaParagraph(`Prompt health: ${briefing.calibration?.promptHealthScore ?? 'not recorded'} | ACO counts: ${JSON.stringify(briefing.calibration?.acoEntityCounts ?? {})}`),
        metaParagraph(`Model: ${briefing.calibration?.model ?? 'not recorded'} | Generated: ${generatedAt}`),
        metaParagraph('Generated by TACITUS PRAXIS. Treat generated analysis as advisory until reviewed against source references.'),
      ],
    }],
  });

  return Buffer.from(await Packer.toBuffer(doc));
}

/**
 * Generate actor dossier as DOCX
 */
export async function generateDossierDOCX(
  situation: Situation,
  actor: string,
  sections: { title: string; content: string }[]
): Promise<Buffer> {
  const doc = new Document({
    sections: [{
      properties: {
        page: { margin: { top: 1440, bottom: 1440, left: 1440, right: 1440 } },
      },
      children: [
        new Paragraph({
          children: [new TextRun({ text: 'ACTOR DOSSIER', font: 'EB Garamond', size: 32, bold: true })],
        }),
        new Paragraph({
          children: [new TextRun({ text: actor, font: 'EB Garamond', size: 28 })],
          spacing: { after: 100 },
        }),
        metaParagraph(`Situation: ${situation.name} | ${new Date().toLocaleDateString()}`),
        divider(),
        ...sections.flatMap((s) => [
          headerParagraph(s.title, HeadingLevel.HEADING_2),
          bodyParagraph(s.content),
        ]),
        divider(),
        metaParagraph('Generated by TACITUS PRAXIS — Conflict Intelligence Platform'),
      ],
    }],
  });

  return Buffer.from(await Packer.toBuffer(doc));
}

