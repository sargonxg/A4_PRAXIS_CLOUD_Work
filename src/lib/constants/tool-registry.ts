// ── Lookup helpers ─────────────────────────────────────────────────────────

export const TOOL_BY_ID = Object.fromEntries(
  TOOL_REGISTRY.map((t) => [t.id, t])
) as Record<string, ToolDefinition>;

export const TOOLS_BY_CATEGORY = TOOL_REGISTRY.reduce(
  (acc, tool) => {
    if (!acc[tool.category]) acc[tool.category] = [];
    acc[tool.category].push(tool);
    return acc;
  },
  {} as Record<string, ToolDefinition[]>
);

export const getToolById = (id: string): ToolDefinition | undefined => TOOL_BY_ID[id];
export const getToolsByCategory = (category: string): ToolDefinition[] => TOOLS_BY_CATEGORY[category] ?? [];
export const getRelatedTools = (toolId: string): ToolDefinition[] => {
  const tool = TOOL_BY_ID[toolId];
  if (!tool) return [];
  return tool.relatedTools.map((id) => TOOL_BY_ID[id]).filter(Boolean) as ToolDefinition[];
};
